//! Interactive Agent CLI TUI & Tmux Driver.
//!
//! Spawns, monitors, and steers interactive coding agent CLIs ([`agy`], [`grok`], [`codex`], [`claude`])
//! inside persistent terminal sessions (tmux panes / PTY).
//!
//! # Architecture
//!
//! - **Dual-Channel Hybrid Extractor**: Combines active VT100 terminal screen captures
//!   (`tmux capture-pane`) with side-channel disk transcript correlation (`transcript.jsonl`, `chat_history.jsonl`)
//!   for lossless output capture without viewport truncation.
//! - **Bracketed Paste Injection**: Submits multi-line prompts safely without premature newline execution.
//! - **Live Human Attachability**: Allows human co-piloting via `tmux -L openduck attach -t <session_id>`.
//! - **Lifecycle & Resource Reclamation**: Automatic idle timeout (`idle_timeout_mins`) and exited
//!   session grace periods (`exited_retention_mins`).
//!
//! Exposes the [`TuiAgentServer`] Model Context Protocol (MCP) server with tools:
//! `tui_agent_start`, `tui_agent_prompt`, `tui_agent_read`, `tui_agent_keys`, `tui_agent_list`, and `tui_agent_stop`.

