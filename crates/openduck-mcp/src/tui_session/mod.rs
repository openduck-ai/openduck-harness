const WORKING_DIR_HEADER: &str = "agent-working-dir";

fn default_true() -> bool {
    true
}

#[derive(Debug, Serialize, Deserialize, JsonSchema)]
pub struct TuiAgentStartParams {
    /// Agent CLI to spawn: agy | grok | codex | claude | custom
    pub agent: String,
    /// Working directory for the agent session. Defaults to goose's current project directory.
    #[serde(default)]
    pub cwd: Option<String>,
    /// Model slug override (for example gemini-3.1-pro-high, grok-4.6)
    #[serde(default)]
    pub model: Option<String>,
    /// Reasoning effort: low, medium, or high
    #[serde(default)]
    pub effort: Option<String>,
    /// Auto-approve permissions and interactive modals (default true)
    #[serde(default = "default_true")]
    pub auto_approve: bool,
    /// Existing conversation or session ID to resume
    #[serde(default)]
    pub resume_id: Option<String>,
    /// Initial prompt to inject immediately once the TUI settles
    #[serde(default)]
    pub initial_prompt: Option<String>,
    /// Custom session identifier (autogenerated if omitted)
    #[serde(default)]
    pub session_id: Option<String>,
    /// Custom tmux socket name (default "openduck")
    #[serde(default)]
    pub socket_name: Option<String>,
    /// Terminal columns (default 160)
    #[serde(default)]
    pub cols: Option<u16>,
    /// Terminal rows (default 48)
    #[serde(default)]
    pub rows: Option<u16>,
    /// Extra arguments passed to the CLI
    #[serde(default)]
    pub extra_args: Option<Vec<String>>,
    /// HTTPS proxy URL for this session (for example http://127.0.0.1:2087).
    /// Overrides HTTPS_PROXY and https_proxy in the spawned CLI environment.
    #[serde(default)]
    pub https_proxy: Option<String>,
    /// Idle timeout in minutes before an inactive session is reclaimed.
    #[serde(default)]
    pub idle_timeout_mins: Option<u64>,
    /// Retention time in minutes to keep an exited session for inspection before reclaiming.
    #[serde(default)]
    pub exited_retention_mins: Option<u64>,
}

#[derive(Debug, Serialize, Deserialize, JsonSchema)]
pub struct TuiAgentPromptParams {
    /// Session ID returned by tui_agent_start
    pub session_id: String,
    /// Prompt or slash command to inject into the TUI composer
    pub prompt: String,
    /// Wait for turn completion before returning (default true)
    #[serde(default = "default_true")]
    pub wait: bool,
    /// Timeout in seconds if wait is true (default 600)
    #[serde(default)]
    pub timeout_secs: Option<u64>,
}

#[derive(Debug, Serialize, Deserialize, JsonSchema)]
pub struct TuiAgentReadParams {
    /// Session ID
    pub session_id: String,
    /// Number of scrollback lines to capture (default 120)
    #[serde(default)]
    pub scrollback_lines: Option<i32>,
    /// Include raw ANSI color codes in screen snapshot (default false)
    #[serde(default)]
    pub include_ansi: bool,
}

#[derive(Debug, Serialize, Deserialize, JsonSchema)]
pub struct TuiAgentKeysParams {
    /// Session ID
    pub session_id: String,
    /// List of keystrokes to send (e.g. ["Escape"], ["y", "Enter"], ["C-c"], ["Up", "Enter"])
    pub keys: Vec<String>,
}

#[derive(Debug, Serialize, Deserialize, JsonSchema)]
pub struct TuiAgentListParams {
    /// Include a preview of the recent screen for each session
    #[serde(default)]
    pub include_screen_preview: bool,
}

#[derive(Debug, Serialize, Deserialize, JsonSchema)]
pub struct TuiAgentStopParams {
    /// Session ID
    pub session_id: String,
}

#[derive(Clone)]
pub struct TuiAgentServer {
    tool_router: ToolRouter<Self>,
    instructions: String,
    manager: Arc<TuiSessionManager>,
}

impl Default for TuiAgentServer {
    fn default() -> Self {
        Self::new()
    }
}

#[tool_router(router = tool_router)]
impl TuiAgentServer {
    pub fn new() -> Self {
        let instructions = formatdoc! {r#"
            The Interactive Agent CLI TUI & Tmux Driver extension is enabled.
            Use it to run persistent, interactive coding agent CLIs (agy, grok, codex, claude) inside tmux sessions.

            Features:
            - Warm, persistent sessions with zero cold-start across turns
            - Multi-line bracketed paste injection and slash command support (/plan, /compact, /status)
            - Live human attachability via `tmux -L openduck attach -t <session_id>`
            - Dual-channel response reading (lossless transcript correlation + clean visual TUI capture)
            - Interactive question & modal answering via `tui_agent_keys`
        "#};

        Self {
            tool_router: Self::tool_router(),
            instructions,
            manager: Arc::new(TuiSessionManager::default()),
        }
    }

    pub fn with_manager(manager: Arc<TuiSessionManager>) -> Self {
        let mut server = Self::new();
        server.manager = manager;
        server
    }

    /// Start a persistent agent CLI session inside tmux (agy, grok, codex, claude).
    #[tool(
        name = "tui_agent_start",
        description = "Spawns an interactive coding agent CLI (agy, grok, codex, claude) inside a persistent tmux session. Returns session_id and attach command."
    )]
    pub async fn tui_agent_start(
        &self,
        params: Parameters<TuiAgentStartParams>,
        context: RequestContext<RoleServer>,
    ) -> Result<CallToolResult, ErrorData> {
        let params = params.0;
        let kind = AgentCliKind::from_str(&params.agent)
            .map_err(|e| ErrorData::new(ErrorCode::INVALID_PARAMS, e.to_string(), None))?;

        let cwd = resolve_cwd(params.cwd.as_deref(), &context);
        let session_id = params
            .session_id
            .unwrap_or_else(|| format!("{}_{}", kind, chrono::Utc::now().timestamp_millis()));

        let config = TuiSessionConfig {
            session_id: session_id.clone(),
            kind,
            cwd,
            model: params.model,
            effort: params.effort,
            auto_approve: params.auto_approve,
            resume_id: params.resume_id,
            cols: params.cols.unwrap_or(160),
            rows: params.rows.unwrap_or(48),
            extra_args: params.extra_args.unwrap_or_default(),
            https_proxy: params.https_proxy,
            env: Vec::new(),
            idle_timeout_mins: params.idle_timeout_mins,
            exited_retention_mins: params.exited_retention_mins,
        };

        let handle = self.manager.start_session(config).await.map_err(|e| {
            ErrorData::new(
                ErrorCode::INTERNAL_ERROR,
                format!("Failed to start TUI session: {e}"),
                None,
            )
        })?;

        let mut initial_turn = None;
        if let Some(prompt) = params.initial_prompt {
            if kind != AgentCliKind::Agy {
                tokio::time::sleep(Duration::from_millis(800)).await;
            }
            match handle
                .send_prompt(&prompt, true, Duration::from_secs(600))
                .await
            {
                Ok(turn) => initial_turn = Some(turn),
                Err(e) if kind == AgentCliKind::Agy => {
                    return Err(ErrorData::new(
                        ErrorCode::INTERNAL_ERROR,
                        format!(
                            "Session '{session_id}' started, but initial prompt submission failed: {e}. Inspect this session before resending."
                        ),
                        None,
                    ));
                }
                Err(e) => {
                    tracing::warn!("Failed initial prompt injection: {e}");
                }
            }
        }

        let attach_cmd = handle.backend.attach_command(&session_id);
        let screen = handle
            .backend
            .capture_screen(&session_id, false, Some(30))
            .await
            .unwrap_or_default();

        let alive = handle
            .backend
            .is_alive(&session_id)
            .await
            .map_err(|e| ErrorData::new(ErrorCode::INTERNAL_ERROR, e.to_string(), None))?;
        let state = if alive {
            handle.profile.classify_screen(&screen)
        } else {
            TuiPaneState::Exited { exit_code: None }
        };

        let payload = serde_json::json!({
            "session_id": session_id,
            "agent": kind.to_string(),
            "pid": handle.pid,
            "attach_command": attach_cmd,
            "initial_screen": screen,
            "initial_turn": initial_turn,
            "state": state,
        });

        Ok(CallToolResult::success(vec![ContentBlock::text(
            serde_json::to_string_pretty(&payload).unwrap_or_default(),
        )]))
    }

    /// Submit a prompt to an active agent CLI TUI session via bracketed paste.
    #[tool(
        name = "tui_agent_prompt",
        description = "Injects a prompt or command into the agent's TUI composer, presses Enter, and reads the response."
    )]
    pub async fn tui_agent_prompt(
        &self,
        params: Parameters<TuiAgentPromptParams>,
    ) -> Result<CallToolResult, ErrorData> {
        let params = params.0;
        let handle = self
            .manager
            .get_session(&params.session_id)
            .await
            .map_err(|e| ErrorData::new(ErrorCode::INVALID_PARAMS, e.to_string(), None))?;

        let timeout = Duration::from_secs(params.timeout_secs.unwrap_or(600));
        let turn = handle
            .send_prompt(&params.prompt, params.wait, timeout)
            .await
            .map_err(|e| {
                ErrorData::new(
                    ErrorCode::INTERNAL_ERROR,
                    format!("Error driving prompt in TUI session: {e}"),
                    None,
                )
            })?;

        Ok(CallToolResult::success(vec![ContentBlock::text(
            serde_json::to_string_pretty(&turn).unwrap_or_default(),
        )]))
    }

    /// Read the live screen and state of an agent TUI session.
    #[tool(
        name = "tui_agent_read",
        description = "Inspects the current screen snapshot, pane state (idle_prompt, working, waiting_approval), and latest output from an agent TUI session."
    )]
    pub async fn tui_agent_read(
        &self,
        params: Parameters<TuiAgentReadParams>,
    ) -> Result<CallToolResult, ErrorData> {
        let params = params.0;
        let handle = self
            .manager
            .get_session(&params.session_id)
            .await
            .map_err(|e| ErrorData::new(ErrorCode::INVALID_PARAMS, e.to_string(), None))?;

        let turn = handle
            .read_state(params.scrollback_lines, params.include_ansi)
            .await
            .map_err(|e| ErrorData::new(ErrorCode::INTERNAL_ERROR, e.to_string(), None))?;

        Ok(CallToolResult::success(vec![ContentBlock::text(
            serde_json::to_string_pretty(&turn).unwrap_or_default(),
        )]))
    }

    /// Send raw keystrokes to an agent TUI session.
    #[tool(
        name = "tui_agent_keys",
        description = "Sends keystrokes directly to the TUI (e.g. ['Escape'], ['y', 'Enter'], ['C-c'], ['Down', 'Enter']) to answer prompts, approve modals, or interrupt."
    )]
    pub async fn tui_agent_keys(
        &self,
        params: Parameters<TuiAgentKeysParams>,
    ) -> Result<CallToolResult, ErrorData> {
        let params = params.0;
        let handle = self
            .manager
            .get_session(&params.session_id)
            .await
            .map_err(|e| ErrorData::new(ErrorCode::INVALID_PARAMS, e.to_string(), None))?;

        handle
            .send_keys(&params.keys)
            .await
            .map_err(|e| ErrorData::new(ErrorCode::INTERNAL_ERROR, e.to_string(), None))?;

        Ok(CallToolResult::success(vec![ContentBlock::text(format!(
            "Sent keys {:?} to session {}",
            params.keys, params.session_id
        ))]))
    }

    /// List all active persistent TUI agent sessions.
    #[tool(
        name = "tui_agent_list",
        description = "Lists all running agent CLI sessions, their states, PIDs, and tmux attach commands."
    )]
    pub async fn tui_agent_list(
        &self,
        params: Parameters<TuiAgentListParams>,
    ) -> Result<CallToolResult, ErrorData> {
        let summaries = self
            .manager
            .list_sessions(params.0.include_screen_preview)
            .await;

        Ok(CallToolResult::success(vec![ContentBlock::text(
            serde_json::to_string_pretty(&summaries).unwrap_or_default(),
        )]))
    }

    /// Stop and terminate an agent TUI session.
    #[tool(
        name = "tui_agent_stop",
        description = "Gracefully interrupts and stops an agent TUI session, destroying its tmux pane."
    )]
    pub async fn tui_agent_stop(
        &self,
        params: Parameters<TuiAgentStopParams>,
    ) -> Result<CallToolResult, ErrorData> {
        let session_id = params.0.session_id.trim();
        self.manager
            .stop_session(session_id)
            .await
            .map_err(|e| ErrorData::new(ErrorCode::INTERNAL_ERROR, e.to_string(), None))?;

        Ok(CallToolResult::success(vec![ContentBlock::text(format!(
            "Session '{session_id}' stopped"
        ))]))
    }
}

#[tool_handler(router = self.tool_router)]
impl ServerHandler for TuiAgentServer {
    fn get_info(&self) -> ServerInfo {
        InitializeResult::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new(
                "goose-tui-agent",
                env!("CARGO_PKG_VERSION"),
            ))
            .with_instructions(self.instructions.clone())
    }
}

fn extract_working_dir_from_meta(meta: &MetaObject) -> Option<PathBuf> {
    meta.0
        .get(WORKING_DIR_HEADER)
        .and_then(|v| v.as_str())
        .filter(|s| !s.is_empty())
        .map(PathBuf::from)
}

fn resolve_cwd(explicit: Option<&str>, context: &RequestContext<RoleServer>) -> PathBuf {
    if let Some(cwd) = explicit.map(str::trim).filter(|s| !s.is_empty()) {
        return PathBuf::from(cwd);
    }
    extract_working_dir_from_meta(&context.meta)
        .or_else(|| env::current_dir().ok())
        .unwrap_or_else(|| PathBuf::from("."))
}
